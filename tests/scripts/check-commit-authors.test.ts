import { createHash } from 'node:crypto'
import { describe, expect, test } from 'vitest'
import {
  type CommitInfo,
  checkLastLine,
  explain,
  findProblems,
  namesHidden,
  OWNER,
  type Person,
  stripToolFooter,
} from '../../scripts/check-commit-authors.ts'

// A made-up hidden name, so this test never holds a real one, kept as HIDDEN_NAMES keeps a display name: lower case,
// its words joined by nothing.
const HIDDEN = [createHash('sha256').update('thequietheron').digest('hex')]

const owner: Person = { name: OWNER.name, email: OWNER.email, login: OWNER.login }
const claude: Person = { name: 'Claude', email: 'noreply@anthropic.com', login: null }
const stranger: Person = { name: 'Sam Rivers', email: 'sam@example.com', login: 'samr' }
const github: Person = { name: 'GitHub', email: 'noreply@github.com', login: 'web-flow' }

function commit(author: Person, extra: Partial<CommitInfo> = {}): CommitInfo {
  return { sha: '0123456789abcdef', author, committer: author, message: 'feat: a change', ...extra }
}

describe('who a commit may come from', () => {
  test('the Owner, named exactly, passes', () => {
    expect(findProblems([commit(owner)], 'A change', 'What it does.')).toEqual([])
  })

  test('the Owner on the web (GitHub as committer) passes', () => {
    expect(findProblems([commit(owner, { committer: github })], 'A change', '')).toEqual([])
  })

  test('someone else keeps their own name', () => {
    expect(findProblems([commit(stranger)], 'A change', '')).toEqual([])
  })

  test('Claude fails, as author and as committer', () => {
    const problems = findProblems([commit(claude)], 'A change', '')
    expect(problems.map((p) => p.what)).toEqual([
      expect.stringContaining('its author is Claude <noreply@anthropic.com>'),
      expect.stringContaining('its committer is Claude <noreply@anthropic.com>'),
    ])
  })

  test('his GitHub login with any other name fails', () => {
    const renamed: Person = { name: 'Another Name', email: 'other@example.com', login: OWNER.login }
    expect(findProblems([commit(renamed)], 'A change', '')).toHaveLength(2)
  })

  test('his name with another email fails', () => {
    const wrongEmail: Person = { name: OWNER.name, email: 'someone@example.com', login: null }
    expect(findProblems([commit(wrongEmail)], 'A change', '')).toHaveLength(2)
  })

  test('his email with the name in another case fails', () => {
    const wrongCase: Person = { name: 'mcthaydt', email: OWNER.email.toUpperCase(), login: null }
    expect(findProblems([commit(wrongCase)], 'A change', '')).toHaveLength(2)
  })

  test('the Owner as author but Claude as committer fails once, for the committer', () => {
    const problems = findProblems([commit(owner, { committer: claude })], 'A change', '')
    expect(problems).toHaveLength(1)
    expect(problems[0]?.what).toContain('its committer')
  })

  test('a problem names the commit by its short id', () => {
    expect(findProblems([commit(claude)], 'A change', '')[0]?.where).toBe('commit 0123456')
  })
})

describe('Claude credits', () => {
  const trailers = [
    'Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>',
    'co-authored-by: claude <noreply@anthropic.com>',
    'Claude-Session: https://claude.ai/code/session_01',
    'Generated with [Claude Code](https://claude.com/claude-code)',
    '🤖 Generated with Claude Code',
    '_Generated by [Claude Code](https://claude.ai/code/session_01)_',
    'Generated by Claude Code',
    'Created with [Claude Code](https://claude.com/claude-code)',
    'Written by Claude',
  ]

  test.each(trailers)('a commit message with "%s" fails', (line) => {
    const problems = findProblems([commit(owner, { message: `feat: a change\n\nWhy.\n\n${line}` })], 'A', '')
    expect(problems).toHaveLength(1)
    expect(problems[0]?.kind).toBe('credit-in-commit')
    expect(problems[0]?.what).toContain(line)
  })

  test.each(trailers)('a pull request description with "%s" fails', (line) => {
    const problems = findProblems([commit(owner)], 'A change', `What it does.\n\n${line}`)
    expect(problems).toHaveLength(1)
    expect(problems[0]?.kind).toBe('credit-in-text')
  })

  test('a title with a credit fails too', () => {
    expect(findProblems([commit(owner)], 'Generated with Claude Code', '')).toHaveLength(1)
  })

  test('a sentence that only mentions a credit passes', () => {
    const prose =
      'It fails on a Co-Authored-By: Claude line, a Claude-Session line or Generated by Claude Code.'
    expect(findProblems([commit(owner, { message: `ci: a check\n\n${prose}` })], 'A check', prose)).toEqual(
      [],
    )
  })

  test('a person who co-authored with someone else passes', () => {
    const message = 'feat: a change\n\nCo-Authored-By: Sam Rivers <sam@example.com>'
    expect(findProblems([commit(owner, { message })], 'A change', '')).toEqual([])
  })

  test("the project's own credit line in a description passes", () => {
    const body = [
      '<!-- claude-projects-attribution: {"github_login":"mcthaydt"} -->',
      '_Requested by **McThayDT** · [project thread](https://claude.ai/code/project/chan_1?thread=cmsg_1)_',
    ].join('\n')
    expect(findProblems([commit(owner)], 'A change', body)).toEqual([])
  })
})

describe("the Owner's other names", () => {
  test('a description that names him otherwise fails', () => {
    const body =
      '_Requested by **The Quiet Heron** · [project thread](https://claude.ai/code/project/chan_1)_'
    const problems = findProblems([commit(owner)], 'A change', body, HIDDEN)
    expect(problems).toHaveLength(1)
    expect(problems[0]?.kind).toBe('name-in-text')
  })

  test('a title or a commit message that names him otherwise fails', () => {
    expect(findProblems([commit(owner)], 'For the quiet-heron', '', HIDDEN)[0]?.kind).toBe('name-in-text')
    const message = 'feat: a change\n\nAsked for by The Quiet Heron.'
    const problems = findProblems([commit(owner, { message })], 'A change', '', HIDDEN)
    expect(problems.map((p) => p.kind)).toEqual(['name-in-commit'])
  })

  test('the name is found in any case, spacing or punctuation, and only as whole words in order', () => {
    expect(namesHidden('THE QUIET HERON', HIDDEN)).toBe(true)
    expect(namesHidden('thequietheron', HIDDEN)).toBe(true)
    expect(namesHidden('the heron is quiet', HIDDEN)).toBe(false)
  })

  test('the credit line with his name now passes', () => {
    const body = '_Requested by **McThayDT** · [project thread](https://claude.ai/code/project/chan_1)_'
    expect(findProblems([commit(owner)], 'A change', body, HIDDEN)).toEqual([])
  })

  test('the real hidden names are kept only as hashes', () => {
    expect(namesHidden('Requested by **McThayDT**')).toBe(false)
  })
})

describe('the message a person reads', () => {
  test('a wrong name comes with the three commands that fix it', () => {
    const text = explain(findProblems([commit(claude)], 'A change', ''), 'main')
    expect(text).toContain('commit 0123456: its author is Claude <noreply@anthropic.com>')
    expect(text).toContain(`git config user.name "${OWNER.name}" && git config user.email "${OWNER.email}"`)
    expect(text).toContain('git rebase origin/main --exec "git commit --amend --no-edit --reset-author"')
    expect(text).toContain('git push --force-with-lease')
  })

  test('a credit in a commit says how to reword it, and one in the text says where to click', () => {
    const problems = findProblems(
      [commit(owner, { message: 'x\n\nClaude-Session: y' })],
      'A change',
      'Generated with Claude Code',
    )
    const text = explain(problems, 'main')
    expect(text).toContain('git rebase -i origin/main')
    expect(text).toContain('press the pencil by the description')
    expect(text).not.toContain('--reset-author')
  })

  test('a name in the description says where to write the right one', () => {
    const text = explain(findProblems([commit(owner)], 'A change', 'By the quiet heron.', HIDDEN), 'main')
    expect(text).toContain(`write ${OWNER.name} where the other name is`)
  })
})

describe("the last line of the Owner's pull request", () => {
  const credit = `Requested by **${OWNER.name}**`

  test('a description that ends with the Claude Code footer fails, and says what the last line is', () => {
    const body = `What it does.\n\n${credit}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_`
    const problem = checkLastLine(body, OWNER.login)
    expect(problem?.kind).toBe('last-line')
    expect(problem?.what).toContain('_Generated by [Claude Code](https://claude.ai/code)_')
    expect(problem?.what).toContain(credit)
  })

  test('a description with no credit line fails', () => {
    expect(checkLastLine('What it does.', OWNER.login)?.kind).toBe('last-line')
  })

  test('an empty description fails', () => {
    expect(checkLastLine('', OWNER.login)?.kind).toBe('last-line')
  })

  test('a description that ends with the credit line, then blank lines, passes', () => {
    expect(checkLastLine(`What it does.\n\n${credit}\n\n\n`, OWNER.login)).toBeNull()
  })

  test('the login is matched in any case', () => {
    expect(checkLastLine('What it does.', 'McThayDT')?.kind).toBe('last-line')
  })

  test('a pull request someone else opened is not held to it', () => {
    expect(checkLastLine('What it does.', 'samr')).toBeNull()
    expect(checkLastLine('What it does.', null)).toBeNull()
  })

  test('the message says where to fix it', () => {
    const problem = checkLastLine('What it does.', OWNER.login)
    expect(problem).not.toBeNull()
    const text = explain(problem === null ? [] : [problem], 'main')
    expect(text).toContain(`make ${credit} the last line`)
  })
})

describe('the footer the cloud tool adds to every pull request description', () => {
  const body = 'What it does.\n\nRequested by **McThayDT**'
  test('comes off, with the rule above it, so the description ends with the credit line again', () => {
    expect(stripToolFooter(`${body}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_`)).toBe(body)
    expect(
      stripToolFooter(`${body}\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01ab)_\n`),
    ).toBe(body)
  })
  test('a description without it is left exactly as it is', () => {
    expect(stripToolFooter(body)).toBe(body)
    expect(stripToolFooter(`${body}\n\n---\nA rule someone wrote.`)).toBe(
      `${body}\n\n---\nA rule someone wrote.`,
    )
  })
  test('only the footer at the very end comes off: a credit anywhere else still fails the check', () => {
    const inside = `_Generated by [Claude Code](https://claude.ai/code)_\n\n${body}`
    expect(stripToolFooter(inside)).toBe(inside)
    expect(findProblems([], 'A change', inside)).not.toEqual([])
  })
})
